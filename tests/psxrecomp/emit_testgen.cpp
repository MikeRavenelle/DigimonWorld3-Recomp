// Build-time tool: recompiles every program of test_programs.h with psxrecomp and writes
//   emitted_funcs.c   - all emitted functions
//   emitted_tables.c  - dw3_segments[] / dw3_segment_count (one segment per program)
//   emitted_tests.inc - manifest for test_emitter (name, base, entry, words, entry function)
// Usage: emit_testgen <out_dir>

#include <cstdio>
#include <cstdlib>
#include <filesystem>
#include <fstream>
#include <map>

#include "psxrecomp/analysis.h"
#include "psxrecomp/emitter.h"
#include "test_programs.h"

using namespace psxrecomp;

namespace {

void write_file(const std::filesystem::path& p, const std::string& text) {
    std::ofstream f(p, std::ios::binary);
    f << text;
    if (!f) {
        std::fprintf(stderr, "emit_testgen: cannot write %s\n", p.string().c_str());
        std::exit(1);
    }
}

}  // namespace

int main(int argc, char** argv) {
    if (argc != 2) {
        std::fprintf(stderr, "usage: emit_testgen <out_dir>\n");
        return 2;
    }
    std::filesystem::path out = argv[1];
    std::filesystem::create_directories(out);

    auto progs = tp::build_test_programs();
    std::vector<CodeSegment> segs;
    segs.reserve(progs.size());
    for (const auto& tp : progs) {
        masm::Program p(tp.base);
        for (uint32_t w : tp.words) p.emit(w);
        segs.push_back(p.segment(tp.name.c_str()));
    }

    std::vector<AnalysisResult> results;
    results.reserve(progs.size());
    std::string funcs = "/* Generated by emit_testgen. Do not edit. */\n#include \"dw3/recomp.h\"\n\n";
    std::string inc = "/* Generated by emit_testgen. Do not edit. */\n";
    std::string decls = "extern \"C\" {\n", words = "", table = "static const EmittedTest kEmitted[] = {\n";
    int errors = 0;
    for (std::size_t i = 0; i < progs.size(); ++i) {
        const auto& tp = progs[i];
        AnalysisConfig cfg;
        cfg.entries = {tp.entry};
        cfg.extra_functions.insert(tp.extra_funcs.begin(), tp.extra_funcs.end());
        cfg.scan_data_pointers = false;
        cfg.scan_jal_words = false;
        cfg.gap_fill = false;
        results.push_back(analyze(segs[i], cfg));
        for (const auto& [addr, f] : results[i].functions)
            for (const auto& e : f.errors) {
                std::fprintf(stderr, "%s (%s) function %08X: %s\n", tp.name.c_str(), tp.desc.c_str(), addr, e.c_str());
                ++errors;
            }
        if (!results[i].functions.count(tp.entry)) {
            std::fprintf(stderr, "%s: entry %08X not found\n", tp.name.c_str(), tp.entry);
            ++errors;
        }
        EmitContext ec;
        ec.seg = &segs[i];
        ec.local = &results[i].functions;
        for (const auto& file : emit_segment(ec, 0)) funcs += file.text + "\n";

        char buf[256];
        words += "static const uint32_t w_" + tp.name + "[] = {";
        for (std::size_t k = 0; k < tp.words.size(); ++k) {
            std::snprintf(buf, sizeof(buf), "%s0x%08Xu", k ? ", " : "", tp.words[k]);
            words += buf;
        }
        words += "};\n";
        std::string fn = func_name(tp.name, tp.entry);
        decls += "void " + fn + "(RecompContext* ctx);\n";
        std::snprintf(buf, sizeof(buf), "    {\"%s\", 0x%08Xu, 0x%08Xu, %zu, w_%s, %s},\n", tp.name.c_str(), tp.base,
                      tp.entry, tp.words.size(), tp.name.c_str(), fn.c_str());
        table += buf;
    }
    if (errors) return 1;

    std::vector<TableSegment> ts;
    for (std::size_t i = 0; i < progs.size(); ++i) ts.push_back({&segs[i], &results[i].functions});
    EmittedFile tables = emit_tables(ts);

    inc += "struct EmittedTest {\n    const char* name;\n    uint32_t base, entry;\n    std::size_t word_count;\n"
           "    const uint32_t* words;\n    RecompFunc func;\n};\n";
    inc += decls + "}\n" + words + table + "};\n";
    write_file(out / "emitted_funcs.c", funcs);
    write_file(out / "emitted_tables.c", tables.text);
    write_file(out / "emitted_tests.inc", inc);
    std::printf("emit_testgen: %zu programs\n", progs.size());
    return 0;
}
