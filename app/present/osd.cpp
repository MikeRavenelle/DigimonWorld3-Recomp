int osd_scale(int window_height) { return std::max(2, window_height / 360); }

int osd_padding(int scale) { return 2 * scale; }

void osd_box_size(int chars, int scale, int& w, int& h) {
    w = chars * kOsdGlyph * scale + 2 * osd_padding(scale);
    h = kOsdGlyph * scale + 2 * osd_padding(scale);
}

OsdImage osd_render_text(std::string_view text, int scale, int max_width) {
    OsdImage img;
    scale = std::max(1, scale);
    const int fit = (max_width - 2 * osd_padding(scale)) / (kOsdGlyph * scale);
    const int chars = std::min<int>(static_cast<int>(text.size()), fit);
    if (chars < 1) return img;
    osd_box_size(chars, scale, img.w, img.h);
    img.rgba.assign(static_cast<std::size_t>(img.w) * static_cast<std::size_t>(img.h), kOsdBoxColor);
    const int pad = osd_padding(scale);
    for (int i = 0; i < chars; ++i) {
        const unsigned char c = static_cast<unsigned char>(text[static_cast<std::size_t>(i)]);
        const uint8_t* glyph = kFont[(c >= 0x20 && c <= 0x7E ? c : '?') - 0x20];
        for (int gy = 0; gy < kOsdGlyph; ++gy)
            for (int gx = 0; gx < kOsdGlyph; ++gx) {
                if (!((glyph[gy] >> gx) & 1)) continue;
                const int x0 = pad + (i * kOsdGlyph + gx) * scale;
                const int y0 = pad + gy * scale;
                for (int sy = 0; sy < scale; ++sy)
                    for (int sx = 0; sx < scale; ++sx)
                        img.rgba[static_cast<std::size_t>(y0 + sy) * static_cast<std::size_t>(img.w) +
                                 static_cast<std::size_t>(x0 + sx)] = kOsdTextColor;
            }
    }
    return img;
}

void Osd::show(std::string text, uint64_t now_ms) {
    text_ = std::move(text);
    shown_at_ = now_ms;
    active_ = true;
}

void Osd::set_status(std::string text) { status_ = std::move(text); }

int Osd::x(int window_w) const { return status_shown_ ? window_w - image_.w - margin_ : margin_; }

const OsdImage* Osd::frame(int window_w, int window_h, uint64_t now_ms, float& opacity) {
    const uint64_t age = now_ms >= shown_at_ ? now_ms - shown_at_ : 0;
    if (active_ && age >= kShowMs) active_ = false;
    status_shown_ = !active_;
    if (status_shown_ && status_.empty()) return nullptr;
    const std::string& text = status_shown_ ? status_ : text_;
    if (status_shown_) opacity = kStatusOpacity;
    else opacity = age + kFadeMs > kShowMs ? static_cast<float>(kShowMs - age) / static_cast<float>(kFadeMs) : 1.0f;
    const int scale = osd_scale(window_h);
    margin_ = 2 * scale;
    const int max_width = window_w - 2 * margin_;
    if (text != image_text_ || scale != image_scale_ || max_width != image_width_) {
        image_ = osd_render_text(text, scale, max_width);
        image_text_ = text;
        image_scale_ = scale;
        image_width_ = max_width;
        ++serial_;
    }
    return image_.w > 0 ? &image_ : nullptr;
}

